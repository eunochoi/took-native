const fs = require('node:fs');
const path = require('node:path');
const { runInNewContext } = require('node:vm');
const ts = require('typescript');
const { renderToStaticMarkup } = require('react-dom/server');
const { createElement } = require('react');

const root = path.resolve(__dirname, '..');

function loadModule(file, resolve) {
  const exports = {};
  runInNewContext(
    ts.transpileModule(fs.readFileSync(file, 'utf8'), {
      compilerOptions: {
        module: ts.ModuleKind.CommonJS,
        jsx: ts.JsxEmit.ReactJSX,
        esModuleInterop: true,
      },
    }).outputText,
    { exports, require: resolve },
  );
  return exports;
}

function buildIconAssets() {
  const svgElements = new Proxy(
    { __esModule: true, default: 'svg', Text: 'text' },
    { get: (elements, key) => elements[key] ?? key.toLowerCase() },
  );
  const { SOBER_RECORD_ICONS } = loadModule(
    path.join(root, 'src/components/recordIcons.ts'),
    (name) => {
      if (!name.startsWith('phosphor-react-native/src/icons/')) throw new Error(name);
      const icon = name.split('/').at(-1);
      return { [`${icon}Icon`]: icon };
    },
  );
  const icons = {};
  const definitions = path.join(path.join(root, 'node_modules/phosphor-react-native'), 'src/defs');
  for (const [key, icon] of Object.entries(SOBER_RECORD_ICONS)) {
    const weights = loadModule(path.join(definitions, `${icon}.tsx`), (name) =>
      name === 'react-native-svg' ? svgElements : require(name),
    ).default;
    const body = renderToStaticMarkup(weights.get(key === 'skinPicking' ? 'regular' : 'fill'));
    if (!body) throw new Error(`Missing fill icon: ${key}`);
    icons[key] =
      `<svg xmlns="http://www.w3.org/2000/svg" width="256" height="256" viewBox="0 0 256 256" fill="currentColor">${body}</svg>`;
  }
  const { SoberIcon } = loadModule(path.join(root, 'src/components/SoberIcon.tsx'), (name) => {
    if (name === 'react-native-svg') return svgElements;
    if (name === 'react') return { useId: () => 'widget-age19' };
    if (name === './recordIcons') return { SOBER_RECORD_ICONS };
    if (name.endsWith('/constants')) return { resolveIconColor: () => '#010203' };
    if (name.endsWith('/AppThemeProvider')) return { useAppTheme: () => ({ colors: {}, rem: 15 }) };
    return require(name);
  });
  const badge = SoberIcon({ name: 'age19', size: 256 });
  const { accessible, ...badgeProps } = badge.props;
  icons.age19 = renderToStaticMarkup(
    createElement(badge.type, {
      ...badgeProps,
      xmlns: 'http://www.w3.org/2000/svg',
      fontFamily: 'sans-serif',
    }),
  ).replaceAll('#010203', 'currentColor');

  // Keep old snapshots and old native binaries compatible while icons move to assets.
  const source = ts.createSourceFile(
    'sober.ts',
    fs.readFileSync(path.join(root, 'src/domain/sober.ts'), 'utf8'),
    ts.ScriptTarget.Latest,
  );
  const declaration = source.statements
    .flatMap((statement) =>
      ts.isVariableStatement(statement) ? [...statement.declarationList.declarations] : [],
    )
    .find((value) => value.name.getText(source) === 'SOBER_ICONS');
  const legacy = {};
  runInNewContext(
    ts.transpileModule(`exports.icons = ${declaration.initializer.getText(source)};`, {})
      .outputText,
    { exports: legacy },
  );
  const glyphs = {
    ionicons: require('@expo/vector-icons/build/vendor/react-native-vector-icons/glyphmaps/Ionicons.json'),
    'material-community': require('@expo/vector-icons/build/vendor/react-native-vector-icons/glyphmaps/MaterialCommunityIcons.json'),
  };
  if (Object.keys(legacy.icons).length !== Object.keys(icons).length)
    throw new Error('Incomplete widget icon coverage');
  const legacyKeys = Object.entries(legacy.icons).map(([key, icon]) => {
    if (!icons[key]) throw new Error(`Missing widget icon: ${key}`);
    const font =
      icon.family === 'badge'
        ? 'TmoneyRoundWind-ExtraBold'
        : icon.family === 'ionicons'
          ? 'Ionicons'
          : 'MaterialDesignIcons';
    const glyph =
      icon.family === 'badge' ? '19' : String.fromCodePoint(glyphs[icon.family][icon.name]);
    return `    ${JSON.stringify(`${font}:${glyph}`)}: ${JSON.stringify(key)},`;
  });
  const swift = `// Generated by scripts/render-widget-icons.cjs. Do not edit by hand.
enum SoberWidgetIcons {
  static let keys: Set<String> = [${Object.keys(icons)
    .map((key) => JSON.stringify(key))
    .join(', ')}]
  static let legacyKeys: [String: String] = [
${legacyKeys.join('\n')}
  ]

  static func assetName(key: String?, glyph: String, font: String) -> String {
    let resolved = key.flatMap { keys.contains($0) ? $0 : nil }
      ?? legacyKeys["\\(font):\\(glyph)"] ?? "favorite"
    return "sober-\\(resolved)"
  }
}
`;
  return { icons, swift };
}

// Keep native resources present even when rebuilding without another Expo prebuild.
function syncNativeAssets(projectRoot = root) {
  const icons = JSON.parse(
    fs.readFileSync(path.join(projectRoot, 'src/widgets/sober/icons.json'), 'utf8'),
  );
  const source = path.join(projectRoot, 'assets/widgets/sober-icons');
  const catalog = path.join(projectRoot, 'targets/sober-widget/Assets.xcassets');
  fs.mkdirSync(catalog, { recursive: true });
  const info = { author: 'xcode', version: 1 };
  fs.writeFileSync(path.join(catalog, 'Contents.json'), JSON.stringify({ info }, null, 2) + '\n');
  for (const key of Object.keys(icons)) {
    const name = `sober-${key}`;
    const imageset = path.join(catalog, `${name}.imageset`);
    fs.mkdirSync(imageset, { recursive: true });
    fs.copyFileSync(path.join(source, `${name}.png`), path.join(imageset, 'icon.png'));
    fs.writeFileSync(
      path.join(imageset, 'Contents.json'),
      JSON.stringify(
        {
          images: [{ filename: 'icon.png', idiom: 'universal', scale: '1x' }],
          info,
          properties: { 'template-rendering-intent': 'template' },
        },
        null,
        2,
      ) + '\n',
    );
  }
  const tokens = JSON.parse(
    fs.readFileSync(path.join(projectRoot, 'src/theme/tokens.json'), 'utf8'),
  );
  const textPrimary = tokens.colorValues[tokens.colors.light.textPrimary];
  const textColor = path.join(catalog, 'WidgetTextPrimaryLight.colorset');
  fs.mkdirSync(textColor, { recursive: true });
  fs.writeFileSync(
    path.join(textColor, 'Contents.json'),
    JSON.stringify(
      {
        colors: [
          {
            idiom: 'universal',
            color: {
              'color-space': 'srgb',
              components: {
                red: String(parseInt(textPrimary.slice(1, 3), 16) / 255),
                green: String(parseInt(textPrimary.slice(3, 5), 16) / 255),
                blue: String(parseInt(textPrimary.slice(5, 7), 16) / 255),
                alpha: '1.000',
              },
            },
          },
        ],
        info,
      },
      null,
      2,
    ) + '\n',
  );
  const androidResources = path.join(projectRoot, 'android/app/src/main/res');
  if (fs.existsSync(androidResources)) {
    const drawable = path.join(androidResources, 'drawable');
    fs.mkdirSync(drawable, { recursive: true });
    fs.copyFileSync(
      path.join(projectRoot, 'assets/widgets/sober-preview.png'),
      path.join(drawable, 'sober_preview.png'),
    );
  }
}

async function renderAssets() {
  const { chromium } = require('playwright');
  const { icons, swift } = buildIconAssets();
  const output = path.join(root, 'assets/widgets/sober-icons');
  fs.mkdirSync(output, { recursive: true });
  const browser = await chromium.launch({
    executablePath:
      process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
    headless: true,
  });
  try {
    const page = await browser.newPage({
      viewport: { width: 256, height: 256 },
      deviceScaleFactor: 1,
    });
    for (const [key, svg] of Object.entries(icons)) {
      await page.setContent(`<style>body{margin:0;color:#000}</style>${svg}`);
      await page
        .locator('svg')
        .screenshot({ path: path.join(output, `sober-${key}.png`), omitBackground: true });
    }
    // Android's widget picker and onboarding share this static widget preview.
    const regular = fs
      .readFileSync(path.join(root, 'assets/fonts/TmoneyRoundWindRegular.otf'))
      .toString('base64');
    const bold = fs
      .readFileSync(path.join(root, 'assets/fonts/TmoneyRoundWindExtraBold.otf'))
      .toString('base64');
    const accent = require('../src/theme/tokens.json').colorValues.blueAccent;
    await page.setViewportSize({ width: 457, height: 445 });
    await page.setContent(`<style>
      @font-face{font-family:Tmoney;src:url(data:font/otf;base64,${regular})}
      @font-face{font-family:Tmoney;src:url(data:font/otf;base64,${bold});font-weight:800}
      *{box-sizing:border-box}body{margin:0;background:transparent;font-family:Tmoney;color:#585858}
      .widget{width:457px;height:445px;border-radius:80px;background:white;padding:35px 40px;display:flex;flex-direction:column;align-items:center;justify-content:space-between}
      .heading{display:flex;flex-direction:column;align-items:center;gap:17px}.icon{height:109px;width:109px;display:flex;align-items:center;justify-content:center;color:${accent}}.icon svg{width:69px;height:69px}.name{font-size:40px;line-height:1.25}
      .stats{width:100%;display:flex;flex-direction:column;gap:15px}.elapsed{font-weight:800;font-size:42px;text-align:center;line-height:1.25;white-space:nowrap}.track{height:30px;background:#f0f0f0;border-radius:15px;overflow:hidden}.fill{width:51%;height:100%;background:${accent}}.labels{display:flex;justify-content:space-between;font-size:30px;line-height:1.25}
    </style><div class="widget"><div class="heading"><div class="icon">${icons.oversleep}</div><div class="name">잘자기</div></div><div class="stats"><div class="elapsed">15일 6시간 54분</div><div class="track"><div class="fill"></div></div><div class="labels"><span>목표 1개월</span><span>51.0%</span></div></div></div>`);
    await page.evaluate(() => document.fonts.ready);
    await page.screenshot({
      path: path.join(root, 'assets/widgets/sober-preview.png'),
      omitBackground: true,
    });
    if (process.argv.includes('--preview')) {
      await page.setViewportSize({ width: 1000, height: 1100 });
      await page.setContent(
        `<style>body{margin:0;padding:20px;background:#f3f5f7;font:12px sans-serif;display:grid;grid-template-columns:repeat(7,1fr);gap:10px}.card{height:112px;display:flex;flex-direction:column;align-items:center;justify-content:center;gap:10px;background:white;border-radius:10px}img{width:52px;height:52px}</style>${Object.keys(
          icons,
        )
          .map(
            (key) =>
              `<div class="card"><img src="data:image/png;base64,${fs.readFileSync(path.join(output, `sober-${key}.png`)).toString('base64')}"><span>${key}</span></div>`,
          )
          .join('')}`,
      );
      const preview = path.join(require('node:os').tmpdir(), 'took-widget-icons-preview.png');
      await page.screenshot({ path: preview, fullPage: true });
      console.log(`Preview: ${preview}`);
    }
  } finally {
    await browser.close();
  }
  fs.writeFileSync(
    path.join(root, 'src/widgets/sober/icons.json'),
    JSON.stringify(icons, null, 2) + '\n',
  );
  fs.writeFileSync(path.join(root, 'targets/sober-widget/SoberWidgetIcons.swift'), swift);
  fs.copyFileSync(
    path.join(root, 'node_modules/phosphor-react-native/LICENSE'),
    path.join(output, 'Phosphor-LICENSE.txt'),
  );
  syncNativeAssets();
  console.log(
    `Generated ${Object.keys(icons).length} widget icons and synchronized native resources.`,
  );
}

module.exports = { buildIconAssets, syncNativeAssets };
if (require.main === module && process.argv.includes('--sync-native')) {
  syncNativeAssets();
  console.log('Synchronized native widget resources.');
} else if (require.main === module)
  renderAssets().catch((error) => {
    console.error(error);
    process.exitCode = 1;
  });
